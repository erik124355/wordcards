CREATE DATABASE IF NOT EXISTS wordcards CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE wordcards;
CREATE TABLE IF NOT EXISTS words_users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nickname VARCHAR(30) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS words_lists (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  title VARCHAR(100) NOT NULL,
  description VARCHAR(500) DEFAULT '',
  lang_a VARCHAR(40) NOT NULL,
  lang_b VARCHAR(40) NOT NULL,
  tags VARCHAR(300) DEFAULT '',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES words_users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS words_words (
  id INT AUTO_INCREMENT PRIMARY KEY,
  list_id INT NOT NULL,
  position INT NOT NULL,
  term VARCHAR(200) NOT NULL,
  definition VARCHAR(200) NOT NULL,
  FOREIGN KEY (list_id) REFERENCES words_lists(id) ON DELETE CASCADE
);
